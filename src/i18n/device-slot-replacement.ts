export function useDeviceSlotReplacementCopy() {
  const locale = useLocaleStore();
  return computed(() => copy[uiLocale(locale.code)]);
}

export type SlotCopyPart = { text: string; key?: string; code?: string };
/** Splits a template into literal text and its {placeholders}, so a page can draw a device name with its mono instance
 *  number, or an icon in place of {more}. */
export function slotCopyParts(template: string, values: Record<string, { name: string; code?: string }> = {}): SlotCopyPart[] {
  return template.split(/(\{\w+\})/).filter(Boolean).map((part) => {
    const key = /^\{(\w+)\}$/.exec(part)?.[1];
    if (key === undefined) return { text: part };
    return { key, text: values[key]?.name ?? "", code: values[key]?.code };
  });
}
